test('failed submission preserves the draft; pending withdrawal safely returns it for revision', async ({ page }) => {
  const headers = { Origin: 'http://127.0.0.1:8787', 'X-Woodstop-Request': '1' };
  const email = `retry-${crypto.randomUUID()}@woodstop.test`;
  expect((await page.request.post('/api/account/register', { headers, data: { email, password: 'Local-test-only-42!', displayName: 'Retry tester' } })).status()).toBe(200);
  expect((await page.request.post('/api/account/development-verify', { headers, data: {} })).status()).toBe(200);
  await page.goto('/');
  await page.getByRole('button', { name: 'Save a stand', exact: true }).click();
  await page.getByRole('textbox', { name: 'Short description' }).fill('Only a description is required for this stand.');
  await expect(page.getByRole('button', { name: 'Submit for review' })).toBeEnabled();
  const draftPath = new URL(page.url()).pathname;
  await page.route('**/api/submissions', route => route.request().method() === 'POST' ? route.fulfill({ status: 503, json: { message: 'Temporary test failure' } }) : route.continue());
  await page.getByRole('button', { name: 'Submit for review' }).click();
  await expect(page.getByRole('alert')).toContainText('Temporary test failure');
  await page.reload();
  await expect(page.getByRole('textbox', { name: 'Short description' })).toHaveValue('Only a description is required for this stand.');
  await page.unroute('**/api/submissions');
  await page.getByRole('button', { name: 'Submit for review' }).click();
  await expect(page.getByRole('heading', { name: 'My submissions' })).toBeVisible();
  const items = await (await page.request.get('/api/submissions')).json();
  const submitted = items[0];
  await page.evaluate(() => { IDBDatabase.prototype.transaction = () => { throw new Error('Simulated storage failure'); }; });
  await page.getByRole('button', { name: 'Withdraw to draft' }).click();
  await expect(page.getByRole('alert')).toContainText('Simulated storage failure');
  expect((await (await page.request.get(`/api/submissions/${submitted.id}`)).json()).status).toBe('pending');
  await page.reload();
  await page.getByRole('button', { name: 'Withdraw to draft' }).click();
  await expect(page.getByRole('heading', { name: 'Save a stand' })).toBeVisible();
  expect(new URL(page.url()).pathname).not.toBe(draftPath);
  await expect(page.getByRole('textbox', { name: 'Short description' })).toHaveValue(submitted.content.description);
  const repeatWithdrawal = await page.request.post(`/api/submissions/${submitted.id}/withdraw`, { headers, data: { revision: submitted.revision } });
  expect(repeatWithdrawal.status()).toBe(200);
  await expect(page.getByRole('button', { name: 'Submit for review' })).toBeEnabled();
  await page.getByRole('button', { name: 'Submit for review' }).click();
  await expect(page.getByRole('heading', { name: 'My submissions' })).toBeVisible();
  const after = await (await page.request.get('/api/submissions')).json();
  expect(after).toHaveLength(2);
  expect(after.filter((item: { status: string }) => item.status === 'pending')).toHaveLength(1);
});
